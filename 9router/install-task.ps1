# install-task.ps1 — register (or re-register) the 9Router keep-alive task.
#
# Two modes, chosen automatically:
#
#   * Elevated (Administrator): the task gets an AtStartup trigger and an S4U
#     principal, so 9Router is up at boot, before anyone logs in. No password is
#     stored (S4U = "run whether user is logged on or not" without credentials).
#
#   * Not elevated: Windows blocks "run whether logged on or not" tasks for
#     normal users, so the task runs hidden at logon instead. It still restarts
#     on failure and survives lock/sleep. To upgrade to boot-start, run this
#     file once from an elevated prompt:
#         Start-Process powershell -Verb RunAs -ArgumentList '-NoProfile','-ExecutionPolicy','Bypass','-File','C:\tools\9router\install-task.ps1'
#
# Idempotent: re-running replaces the existing task definition.
#
#   powershell.exe -NoProfile -ExecutionPolicy Bypass -File C:\tools\9router\install-task.ps1
$ErrorActionPreference = "Stop"

$root = $PSScriptRoot
$configPath = Join-Path $root "config.json"
if (-not (Test-Path $configPath)) { throw "Missing config: $configPath" }
$config = Get-Content $configPath -Raw | ConvertFrom-Json

$supervisor = Join-Path $root "supervisor.cjs"
if (-not (Test-Path $supervisor)) { throw "Missing supervisor: $supervisor" }

$node = $config.nodePath
if (-not (Test-Path $node)) { $node = (Get-Command node.exe -ErrorAction Stop).Source }

$taskName = "9Router"
$userId = "$env:COMPUTERNAME\$env:USERNAME"
$isAdmin = (New-Object Security.Principal.WindowsPrincipal([Security.Principal.WindowsIdentity]::GetCurrent())).IsInRole(
    [Security.Principal.WindowsBuiltInRole]::Administrator)

# --- hidden launcher -------------------------------------------------------
# Task Scheduler shows a console window for interactive console apps. Wrapping
# node in a WScript shim launched with window style 0 keeps it invisible, and
# `sh.Run(..., 0, True)` keeps the task instance alive as long as node runs — so
# "restart on failure" still works (the shim propagates node's exit code).
# NOTE: the Windows Script Host parser requires CRLF line endings — an LF-only
# .vbs fails with "Expected end of statement" and then hangs on a modal dialog,
# so the file is written with explicit `r`n and ASCII encoding.
$vbsPath = Join-Path $root "launch-supervisor.vbs"
$vbsLines = @(
    "' launch-supervisor.vbs - generated by install-task.ps1, do not edit by hand.",
    "' Starts the 9Router supervisor with no visible window and forwards its exit code.",
    'Set sh = CreateObject("WScript.Shell")',
    ('code = sh.Run("""{0}"" ""{1}""", 0, True)' -f $node, $supervisor),
    "' A killed process yields -1 (0xFFFFFFFF), which Task Scheduler reads as",
    "' 'terminated' and will NOT retry. Normalise any failure to 1 so the task's",
    "' restart-on-failure policy actually kicks in.",
    "If code <> 0 Then WScript.Quit 1",
    "WScript.Quit 0"
)
$vbs = ($vbsLines -join "`r`n") + "`r`n"
[System.IO.File]::WriteAllText($vbsPath, $vbs, [System.Text.Encoding]::ASCII)

$action = New-ScheduledTaskAction `
    -Execute (Join-Path $env:SystemRoot "System32\wscript.exe") `
    -Argument "//nologo `"$vbsPath`"" `
    -WorkingDirectory $root

$triggers = @(New-ScheduledTaskTrigger -AtLogOn -User $userId)

# The watchdog: a trigger that repeats every minute, forever. Task Scheduler's
# "restart on failure" setting is NOT reliable for a task whose action simply
# ends with a failure (verified on this machine: LastTaskResult=1, no retry), so
# the repetition is the actual keep-alive. Cost is a scheduler tick per minute;
# while the supervisor runs, MultipleInstances=IgnoreNew makes it a no-op.
# `9r stop` disables the task so an intentional stop stays stopped.
$watchdog = New-ScheduledTaskTrigger -Once -At (Get-Date) `
    -RepetitionInterval (New-TimeSpan -Minutes 1) `
    -RepetitionDuration (New-TimeSpan -Days 3650)
$triggers += $watchdog

if ($isAdmin) {
    $startupTrigger = New-ScheduledTaskTrigger -AtStartup
    $startupTrigger.Delay = "PT20S"
    $triggers = @($startupTrigger) + $triggers
    $principal = New-ScheduledTaskPrincipal -UserId $userId -LogonType S4U -RunLevel Limited
    $mode = "boot + logon (S4U, runs before login)"
} else {
    $principal = New-ScheduledTaskPrincipal -UserId $userId -LogonType Interactive -RunLevel Limited
    $mode = "logon only (not elevated - no boot trigger)"
}

$settings = New-ScheduledTaskSettingsSet `
    -AllowStartIfOnBatteries `
    -DontStopIfGoingOnBatteries `
    -StartWhenAvailable `
    -ExecutionTimeLimit ([TimeSpan]::Zero) `
    -RestartCount 999 `
    -RestartInterval (New-TimeSpan -Minutes 1) `
    -MultipleInstances IgnoreNew `
    -Hidden

Write-Host "[9Router] Registering task '$taskName' for $userId"
Write-Host "[9Router] Mode: $mode"
Write-Host "[9Router] Action: wscript //nologo `"$vbsPath`""

Unregister-ScheduledTask -TaskName $taskName -Confirm:$false -ErrorAction SilentlyContinue

Register-ScheduledTask -TaskName $taskName `
    -Action $action `
    -Trigger $triggers `
    -Principal $principal `
    -Settings $settings `
    -Description "9Router gateway/dashboard on ports 20127 (native) and 20128 (bridge). Hidden, supervised, restarts on failure." `
    -Force | Out-Null

Write-Host "[9Router] Registered. Starting now..."
Start-ScheduledTask -TaskName $taskName
Start-Sleep -Seconds 3

Get-ScheduledTask -TaskName $taskName | Select-Object TaskName, State | Format-Table -AutoSize
Get-ScheduledTaskInfo -TaskName $taskName | Select-Object LastRunTime, LastTaskResult, NextRunTime | Format-List

if (-not $isAdmin) {
    Write-Host ""
    Write-Host "[9Router] NOTE: this task starts at logon, not at boot." -ForegroundColor Yellow
    Write-Host "          Windows blocks 'run whether logged on or not' tasks for non-admin users." -ForegroundColor Yellow
    Write-Host "          For boot-start (up even before you log in), run this once from an elevated prompt:" -ForegroundColor Yellow
    Write-Host "            Start-Process powershell -Verb RunAs -ArgumentList '-NoProfile','-ExecutionPolicy','Bypass','-File','$PSCommandPath'" -ForegroundColor Yellow
}
